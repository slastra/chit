#!/usr/bin/env python3
"""Every platform icon from the mark's masters in assets/brand/.

    python3 tool/brand.py          # from app/; needs rsvg-convert

The treatment is tonal: the mark in on-primary-container on a
primary-container tile. Static icons (Android, web, the Linux fallback) use
chit's default scheme, the seed the app falls back to without wallpaper or
desktop colors; where a platform can recolor, it does: Android 13+ themes the
monochrome layer from the wallpaper, the favicon follows light and dark, and
on the desk tint renders the Linux icon from the desktop scheme
(README, "Icon and mark", has how).
"""
import pathlib, re, subprocess

APP = pathlib.Path(__file__).resolve().parent.parent
BRAND = APP / 'assets/brand'

# chit's default scheme, tonal pair (ColorScheme.fromSeed(0xFF4F7CAC),
# Expressive variant): primaryContainer / onPrimaryContainer
LIGHT = ('#c8ef9d', '#314f0f')
DARK = ('#314f0f', '#c8ef9d')

TILE_RADIUS = 0.22  # the rounded-square tile, as ChitTile draws it
MARK_ON_TILE = 0.6875  # the mark's 256 canvas inside a tile


def paths(cut):
    """The master's paths as (d, evenodd) pairs."""
    svg = (BRAND / f'chit-{cut}.svg').read_text()
    return [(m.group(2), 'evenodd' in m.group(1)) for m in re.finditer(r'<path([^>]*?) d="([^"]+)"', svg)]


def mark_group(cut, ink, scale, dx, dy):
    body = ''.join(
        f'<path fill="{ink}"{" fill-rule=\"evenodd\"" if eo else ""} d="{d}"/>' for d, eo in paths(cut)
    )
    return f'<g transform="translate({dx:g} {dy:g}) scale({scale:g})">{body}</g>'


def tile_svg(cut, tile, ink, bleed=False, mark=MARK_ON_TILE):
    """A 256 tile: rounded square, or full bleed for masked icons."""
    bg = (
        f'<rect width="256" height="256" fill="{tile}"/>'
        if bleed
        else f'<rect width="256" height="256" rx="{256 * TILE_RADIUS:g}" fill="{tile}"/>'
    )
    off = 256 * (1 - mark) / 2
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>chit</title>'
        f'{bg}{mark_group(cut, ink, mark, off, off)}</svg>'
    )


def png(svg, out, size):
    out.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(['rsvg-convert', '-w', str(size), '-h', str(size), '-o', str(out)], input=svg.encode(), check=True)


def android():
    res = APP / 'android/app/src/main/res'
    # Adaptive icon: a 108dp canvas whose middle 66dp circle always shows.
    # The mark's 256 canvas at 0.21 (54dp) keeps its widest points, the base's
    # lower corners, inside that circle under every launcher mask.
    k, off = 0.21, (108 - 256 * 0.21) / 2

    def vector(color):
        group = ''.join(
            f'\n        <path android:fillColor="{color}"{" android:fillType=\"evenOdd\"" if eo else ""}\n'
            f'            android:pathData="{d}"/>'
            for d, eo in paths('icon')
        )
        return (
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<!-- generated by tool/brand.py -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp" android:height="108dp"\n'
            '    android:viewportWidth="108" android:viewportHeight="108">\n'
            f'    <group android:translateX="{off:g}" android:translateY="{off:g}"\n'
            f'        android:scaleX="{k}" android:scaleY="{k}">{group}\n    </group>\n</vector>\n'
        )

    (res / 'drawable/ic_launcher_foreground.xml').write_text(vector(LIGHT[1]))
    # themed icons (Android 13+): the system tints this from the wallpaper
    (res / 'drawable/ic_launcher_monochrome.xml').write_text(vector('#FFFFFFFF'))
    (res / 'values/ic_launcher_background.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tool/brand.py -->\n'
        f'<resources>\n    <color name="ic_launcher_background">{LIGHT[0]}</color>\n</resources>\n'
    )
    adaptive = (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- generated by tool/brand.py -->\n'
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background"/>\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
        '</adaptive-icon>\n'
    )
    (res / 'mipmap-anydpi-v26').mkdir(exist_ok=True)
    (res / 'mipmap-anydpi-v26/ic_launcher.xml').write_text(adaptive)
    # before Android 8: the rounded-square tile as a bitmap
    for dpi, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        png(tile_svg('icon', *LIGHT), res / f'mipmap-{dpi}/ic_launcher.png', px)


def web():
    web = APP / 'web'
    light = tile_svg('tiny', *LIGHT)
    # one favicon for both modes: the tile swaps its pair with the browser's
    fav = light.replace(
        '<title>chit</title>',
        '<title>chit</title><style>@media (prefers-color-scheme: dark){'
        f'rect{{fill:{DARK[0]}}}path{{fill:{DARK[1]}}}}}</style>',
    )
    (web / 'favicon.svg').write_text(fav + '\n')
    png(light, web / 'favicon.png', 32)
    for size in (192, 512):
        png(tile_svg('icon', *LIGHT), web / f'icons/Icon-{size}.png', size)
        # maskable: full bleed, the mark inside the 80% safe circle
        png(tile_svg('icon', *LIGHT, bleed=True, mark=0.58), web / f'icons/Icon-maskable-{size}.png', size)


def linux():
    out = APP / 'linux/packaging'
    out.mkdir(parents=True, exist_ok=True)
    # the fallback icon, until a theme (tint, on the desk) supplies its own
    (out / 'us.lastra.chit.svg').write_text(tile_svg('icon', *LIGHT) + '\n')
    # tint's template: the tonal pair from the desktop palette, the accent
    # laid over the background as the container (tint has no tone math)
    off = 256 * (1 - MARK_ON_TILE) / 2
    (out / 'tint-chit-icon.svg').write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 256 256"><title>chit</title>'
        f'<rect width="256" height="256" rx="{256 * TILE_RADIUS:g}" fill="{{{{background}}}}"/>'
        f'<rect width="256" height="256" rx="{256 * TILE_RADIUS:g}" fill="{{{{accent}}}}" fill-opacity="0.28"/>'
        f'{mark_group("icon", "{{accent}}", MARK_ON_TILE, off, off)}</svg>\n'
    )


if __name__ == '__main__':
    android()
    web()
    linux()
    print('icons written')
